// gencode runs the deterministic OpenAPI codegen pipeline:
// specfilter → oapi-codegen → SPDX header → gofmt.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const (
	spdxLine = "// SPDX-License-Identifier: AGPL-3.0-only"
	genFile  = "internal/openaiapi/gen.go"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	if err := os.Chdir(root); err != nil {
		return err
	}
	tmp, err := os.CreateTemp("", "openai-sub-*.json")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	_ = tmp.Close()
	defer func() { _ = os.Remove(tmpPath) }()

	if err := runCmd(os.Stdout, os.Stderr, "go", "run", "./tools/specfilter",
		"-spec", "api/openai/openapi.json",
		"-ops", "api/openai/operations.txt",
		"-out", tmpPath,
	); err != nil {
		return err
	}
	if err := runCmd(os.Stdout, os.Stderr, "go", "tool", "oapi-codegen",
		"-config", "internal/openaiapi/cfg.yaml",
		tmpPath,
	); err != nil {
		return err
	}
	if err := addSPDX(genFile); err != nil {
		return err
	}
	return runCmd(os.Stdout, os.Stderr, "gofmt", "-w", genFile)
}

func addSPDX(path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	lines := strings.Split(string(raw), "\n")
	generated := ""
	rest := make([]string, 0, len(lines))
	for _, line := range lines {
		if strings.HasPrefix(line, "// SPDX-License-Identifier:") {
			continue
		}
		if generated == "" && strings.Contains(strings.ToLower(line), "code generated") {
			generated = line
			continue
		}
		rest = append(rest, line)
	}
	if generated == "" {
		generated = "// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.8.0 DO NOT EDIT."
	}
	var b strings.Builder
	b.WriteString(spdxLine)
	b.WriteByte('\n')
	b.WriteString(generated)
	b.WriteByte('\n')
	b.WriteString(strings.Join(rest, "\n"))
	if !strings.HasSuffix(b.String(), "\n") {
		b.WriteByte('\n')
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func repoRoot() (string, error) {
	if wd, err := os.Getwd(); err == nil {
		if fileExists(filepath.Join(wd, "api/openai/openapi.json")) {
			return wd, nil
		}
	}
	out, err := exec.Command("go", "env", "GOMOD").Output()
	if err != nil {
		return "", err
	}
	mod := strings.TrimSpace(string(out))
	if mod == "" || mod == os.DevNull {
		wd, err := os.Getwd()
		if err != nil {
			return "", err
		}
		return wd, nil
	}
	return filepath.Dir(mod), nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func runCmd(stdout, stderr *os.File, name string, args ...string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdout = stdout
	cmd.Stderr = stderr
	var buf bytes.Buffer
	if stdout == nil {
		cmd.Stdout = &buf
	}
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	}
	return nil
}
