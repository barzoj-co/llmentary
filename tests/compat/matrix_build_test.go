package compat_test

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/barzoj-co/llmentary/internal/proxy"
)

type matrixCase struct {
	ID       string          `json:"id"`
	Provider string          `json:"provider"`
	Surface  string          `json:"surface"`
	Mode     string          `json:"mode"`
	Target   string          `json:"target"`
	Profile  string          `json:"profile"`
	Path     string          `json:"path"`
	Request  json.RawMessage `json:"request"`
	Want     matrixWant      `json:"want"`
}

type matrixWant struct {
	Status         int    `json:"status"`
	UpstreamCalled bool   `json:"upstream_called"`
	Spec           string `json:"spec"`
	Reject         bool   `json:"reject,omitempty"`
}

const minMatrixCases = 129

func buildMatrix() []matrixCase {
	var out []matrixCase
	for _, provider := range providers {
		for _, surface := range surfaces {
			path, req := requestFor(provider, surface)
			for _, target := range []string{proxy.SpecTargetCompatible, proxy.SpecTargetOpenAI} {
				for _, mode := range []string{"warn", "enforce"} {
					if mode == "enforce" && surface != "chat.json" && surface != "responses.json" {
						continue
					}
					id := strings.Join([]string{provider, surface, shortTarget(target), mode, "relaxed"}, "/")
					out = append(out, matrixCase{
						ID:       id,
						Provider: provider,
						Surface:  surface,
						Mode:     mode,
						Target:   target,
						Profile:  "relaxed",
						Path:     path,
						Request:  req,
						Want:     expectedWant(target, mode, surface, provider, req),
					})
				}
			}
		}
	}
	// Request-side vendor fields: compatible enforce forwards, openai enforce 400s.
	for _, provider := range []string{"ollama", "llamacpp", "deepseek", "groq", "gemini"} {
		req := chatRequest(provider, `"top_k":20`)
		for _, target := range []string{proxy.SpecTargetCompatible, proxy.SpecTargetOpenAI} {
			out = append(out, matrixCase{
				ID:       strings.Join([]string{provider, "chat.json.top_k", shortTarget(target), "enforce", "relaxed"}, "/"),
				Provider: provider,
				Surface:  "chat.json",
				Mode:     "enforce",
				Target:   target,
				Profile:  "relaxed",
				Path:     chatJSONPath,
				Request:  req,
				Want:     expectedWant(target, "enforce", "chat.json", provider, req),
			})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func shortTarget(target string) string {
	if target == proxy.SpecTargetCompatible {
		return "compat"
	}
	return "openai"
}

func expectedWant(target, mode, surface, provider string, req []byte) matrixWant {
	vendorReq := bytes.Contains(req, []byte(`"top_k"`))
	if vendorReq && target == proxy.SpecTargetOpenAI && mode == "enforce" {
		return matrixWant{Status: 400, UpstreamCalled: false, Spec: "findings", Reject: true}
	}
	want := matrixWant{Status: 200, UpstreamCalled: true, Spec: "clean"}
	if target == proxy.SpecTargetCompatible {
		// Compatible response extras are stored as response_shape info
		// and do not count as spec=findings. These fixtures have no
		// request-side warn findings.
		return want
	}
	noisyJSON := provider == "together" || provider == "openrouter" || provider == "groq" || provider == "deepseek"
	if strings.HasPrefix(surface, "responses.") {
		want.Spec = "findings"
		return want
	}
	if surface == "chat.json" && (noisyJSON || provider == "ollama" || provider == "llamacpp" || provider == "mistral" || provider == "gemini" || vendorReq) {
		want.Spec = "findings"
	}
	if surface == "chat.sse" && (provider == "together" || provider == "openrouter") {
		want.Spec = "findings"
	}
	return want
}

func renderCompatMatrix(cases []matrixCase) string {
	var b strings.Builder
	b.WriteString("# OpenAI-compatible CI matrix\n\n")
	b.WriteString("Generated by `tests/compat`. Do not edit by hand. CI fails if this file is stale.\n\n")
	b.WriteString("Rows are fixture-verified wire shapes (no provider API keys, model output content is never asserted).\n")
	fmt.Fprintf(&b, "Case count: **%d** (minimum %d).\n\n", len(cases), minMatrixCases)
	b.WriteString("| ID | Provider | Surface | Target | Mode | Status | Spec |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %d | %s |\n",
			c.ID, c.Provider, c.Surface, c.Target, c.Mode, c.Want.Status, c.Want.Spec)
	}
	b.WriteByte('\n')
	return b.String()
}

func marshalMatrix(cases []matrixCase) []byte {
	raw, err := json.MarshalIndent(cases, "", "  ")
	if err != nil {
		panic(err)
	}
	raw = append(raw, '\n')
	return raw
}
